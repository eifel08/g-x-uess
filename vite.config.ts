/// <reference types="vitest/config" />
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';

/**
 * Emits `sw.js`, an offline service worker that precaches every file of this
 * build. The cache name includes a hash of the file list, so each deploy gets
 * a fresh cache and the old one is deleted on activation.
 */
function offlineServiceWorker(): Plugin {
  return {
    name: 'gxuess-offline-sw',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = ['./', ...Object.keys(bundle).map((f) => `./${f}`)].sort();
      // Public files are copied after the bundle is written; list them here.
      files.push('./favicon.svg', './manifest.webmanifest', './icon-192.png', './icon-512.png', './icon-maskable-512.png', './apple-touch-icon.png');
      let h = 0;
      for (const c of files.join('|')) h = (Math.imul(h, 31) + c.charCodeAt(0)) | 0;
      const version = (h >>> 0).toString(36);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorkerSource(version, files) });
    },
  };
}

function serviceWorkerSource(version: string, files: string[]): string {
  return `// Generated by vite.config.ts: precaches the app so it works offline.
const CACHE = 'gxuess-${version}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('gxuess-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    // Pages: network first so updates arrive, the cached app when offline.
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          if (response.ok) caches.open(CACHE).then((cache) => cache.put('./', copy));
          return response;
        })
        .catch(() => caches.match('./')),
    );
    return;
  }
  // Hashed assets and icons: cache first.
  event.respondWith(caches.match(request).then((hit) => hit || fetch(request)));
});
`;
}

// `base: './'` keeps asset URLs relative so the same build works on static
// hosting (GitHub Pages, Netlify), as an installed PWA, and inside the
// Android WebView app (android/).
//
// `vite build --mode single` builds one JS and one CSS file into dist-single/,
// which scripts/single-file.mjs then inlines into a standalone gxuess.html.
export default defineConfig(({ mode }) => ({
  base: './',
  plugins: [react(), ...(mode === 'single' ? [] : [offlineServiceWorker()])],
  build:
    mode === 'single'
      ? {
          outDir: 'dist-single',
          assetsInlineLimit: Number.MAX_SAFE_INTEGER,
          cssCodeSplit: false,
          chunkSizeWarningLimit: 4096,
          rollupOptions: { output: { inlineDynamicImports: true } },
        }
      : {},
  test: {
    environment: 'node',
    include: ['src/**/*.test.{ts,tsx}'],
  },
}));
